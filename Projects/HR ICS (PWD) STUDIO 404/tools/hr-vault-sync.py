#!/usr/bin/env python3
"""HR ICS (PWD) STUDIO 404: copy project files into this vault folder with versioned names.

How it works
- Put the project's current files in `_incoming/` (same sub-paths as the project files,
  e.g. `_incoming/hiring-forms/webapp/Code.gs`). Memory notes go in `_incoming/memory/`.
- Run:  python3 tools/hr-vault-sync.py            (from this project folder)
- For every file in `_incoming/`:
    * unchanged (same SHA-256 as the vault copy)  -> nothing happens
    * changed  -> old copy is moved to `archive/`, new copy saved with the next version
                  (patch +1 by default: 1.0.0 -> 1.0.1; use --minor or --major for bigger bumps)
    * new      -> saved as v1.0.0 (name from the manifest if it already has one, else derived)
- `hr-vault-manifest.json` is the record of every file; `VERSIONS.md` is regenerated from it.
- Files marked private (applicants' personal data) go to `private/`, which git ignores.
  Mark a new one with:  --private "uploads/hearth/<id>"
- Then it commits this project folder only (never other vault files) in the vault's git repo.
  Use --no-commit to skip that.
"""
import argparse, datetime, hashlib, json, os, shutil, subprocess, sys

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))  # project folder
INCOMING = os.path.join(HERE, "_incoming")
MANIFEST = os.path.join(HERE, "hr-vault-manifest.json")
VERSIONS = os.path.join(HERE, "VERSIONS.md")

# Where each kind of source file goes, by source path prefix (first match wins).
DIRS = [
    ("hiring-forms/webapp/netlify-site/", "deliverables/netlify-site"),
    ("hiring-forms/webapp/", "deliverables/apps-script"),
    ("hiring-forms/", "deliverables/hiring-forms"),
    ("uploads/", "uploads"),
    ("memory/", "notes"),
    ("", "other"),
]
MAGIC = [(b"\x89PNG", ".png"), (b"\xff\xd8\xff", ".jpg"), (b"%PDF", ".pdf"), (b"GIF8", ".gif"),
         (b"PK\x03\x04", ".zip"), (b"RIFF", ".webp")]


def sha(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def bump(v, kind):
    a, b, c = (int(x) for x in v.split("."))
    if kind == "major":
        return f"{a + 1}.0.0"
    if kind == "minor":
        return f"{a}.{b + 1}.0"
    return f"{a}.{b}.{c + 1}"


def guess_ext(path):
    with open(path, "rb") as f:
        head = f.read(8)
    for magic, ext in MAGIC:
        if head.startswith(magic):
            return ext
    return ".bin"


def default_name(src, path):
    folder = next(d for p, d in DIRS if src.startswith(p))
    base = os.path.basename(src)
    stem, ext = os.path.splitext(base)
    if not ext:
        ext = guess_ext(path)
        stem = "ICS-Upload-" + stem[:8]
    elif not stem.startswith("ICS-"):
        stem = "ICS-" + stem
    return f"{folder}/{stem}{ext}"  # version suffix added on save


def versioned(name, version):
    stem, ext = os.path.splitext(name)
    return f"{stem}_v{version}{ext}"


def load():
    if os.path.exists(MANIFEST):
        with open(MANIFEST, encoding="utf-8") as f:
            return json.load(f)
    return {"files": {}}


def save(man):
    with open(MANIFEST, "w", encoding="utf-8", newline="\n") as f:
        json.dump(man, f, indent=2, ensure_ascii=False)
        f.write("\n")


def write_versions(man):
    rows = []
    for src in sorted(man["files"]):
        e = man["files"][src]
        if not e.get("version"):
            continue
        where = "private (not in git)" if e.get("private") else "git"
        path = ("private/" if e.get("private") else "") + versioned(e["name"], e["version"])
        old = ", ".join(f"v{h['version']}" for h in e.get("history", [])) or "-"
        rows.append(f"| `{src}` | `{path}` | v{e['version']} | {e.get('updated', '')} | {old} | {where} |")
    text = f"""# Versions: HR ICS (PWD) STUDIO 404

Generated by `tools/hr-vault-sync.py` from `hr-vault-manifest.json`. Don't edit the table by hand.

## Rules
- Every file starts at **v1.0.0**. Each kind of file has its own version number.
- When a file changes, it gets the next version: small change = patch (1.0.0 -> 1.0.1),
  new feature = minor (1.0.x -> 1.1.0), full redesign = major (1.x -> 2.0.0).
- The old version is never overwritten: it moves to `archive/` (same sub-folder).
- Applicants' personal data (names, phone numbers) is kept in `private/`, which git ignores.
- To deploy a Netlify page, copy it and rename it back to its original name
  (`index.html`, `staff.html`, `eval.html`); see the "Original name" column.

## Current files
| Original name (project files) | Vault file | Version | Updated | Older versions (in archive/) | Stored in |
|---|---|---|---|---|---|
""" + "\n".join(rows) + "\n"
    with open(VERSIONS, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def git(*args):
    return subprocess.run(["git", *args], cwd=HERE, capture_output=True, text=True)


def tidy_locks():
    """Linked shells can't delete files, so git leaves .lock files; rename them (vault git-sync rule)."""
    top = git("rev-parse", "--absolute-git-dir").stdout.strip()
    if not top:
        return
    stamp = datetime.datetime.now().strftime("%Y%m%d%H%M%S")
    for root, dirs, names in os.walk(top):
        if os.path.relpath(root, top).split(os.sep)[0] == "refs":
            continue  # never touch ref locks
        for n in names:
            if n.endswith(".lock"):
                try:
                    os.replace(os.path.join(root, n), os.path.join(top, f"stale-{n[:-5]}-{stamp}"))
                except OSError:
                    pass


def main():
    ap = argparse.ArgumentParser()
    g = ap.add_mutually_exclusive_group()
    g.add_argument("--minor", action="store_true")
    g.add_argument("--major", action="store_true")
    ap.add_argument("--private", action="append", default=[], help="source path to keep out of git")
    ap.add_argument("--no-commit", action="store_true")
    ap.add_argument("-m", "--message", default="")
    a = ap.parse_args()
    kind = "major" if a.major else "minor" if a.minor else "patch"
    today = datetime.date.today().isoformat()

    man = load()
    files = man["files"]
    changes = []
    for root, _, names in os.walk(INCOMING):
        for n in sorted(names):
            p = os.path.join(root, n)
            src = os.path.relpath(p, INCOMING).replace(os.sep, "/")
            h = sha(p)
            e = files.setdefault(src, {})
            if src in a.private:
                e["private"] = True
            e.setdefault("name", default_name(src, p))
            if e.get("sha256") == h:
                continue
            base = os.path.join(HERE, "private") if e.get("private") else HERE
            if e.get("version") and e.get("sha256"):
                old = os.path.join(base, versioned(e["name"], e["version"]))
                if os.path.exists(old):
                    arch = os.path.join(HERE, "private" if e.get("private") else "", "archive",
                                        versioned(e["name"], e["version"]))
                    os.makedirs(os.path.dirname(arch), exist_ok=True)
                    os.replace(old, arch)
                e.setdefault("history", []).append({"version": e["version"], "sha256": e["sha256"],
                                                    "updated": e.get("updated", "")})
                e["version"] = bump(e["version"], kind)
                what = "changed"
            else:
                e["version"] = e.get("version") or "1.0.0"
                what = "new"
            dest = os.path.join(base, versioned(e["name"], e["version"]))
            os.makedirs(os.path.dirname(dest), exist_ok=True)
            shutil.copyfile(p, dest)
            e["sha256"], e["updated"] = h, today
            changes.append(f"{what}: {src} -> {versioned(e['name'], e['version'])}")

    save(man)
    write_versions(man)
    print("\n".join(changes) if changes else "No changes.")
    if a.no_commit or not changes:
        return
    tidy_locks()
    git("add", "--", ".")
    tidy_locks()
    if git("diff", "--cached", "--quiet", "--", ".").returncode == 0:
        print("Nothing to commit.")
        return
    msg = a.message or f"HR ICS: vault sync, {len(changes)} file(s) {today}"
    r = git("commit", "-m", msg + "\n\n" + "\n".join(changes), "--", ".")
    tidy_locks()
    print(r.stdout.strip() or r.stderr.strip())
    sys.exit(r.returncode)


if __name__ == "__main__":
    main()
